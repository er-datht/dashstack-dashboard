/**
 * Filter values for the UI Elements charts gallery filter dropdown.
 *
 * - "all"   → render all three sections (Bar, Pie, Donut)
 * - "bar"   → render only the Bar Chart section
 * - "pie"   → render only the Pie Chart section
 * - "donut" → render only the Donut Chart section
 */
export type FilterValue = "all" | "bar" | "pie" | "donut";
